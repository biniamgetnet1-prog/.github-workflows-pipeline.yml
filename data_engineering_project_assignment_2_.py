def _clean_and_preprocess_data():
    print("Loading data for cleaning and preprocessing...")
    df = pd.read_csv('WA_Fn-UseC_-Telco-Customer-Churn.csv') # Reload as a new task

    df['TotalCharges'] = pd.to_numeric(df['TotalCharges'], errors='coerce')
    df['TotalCharges'].fillna(0, inplace=True)
    df.drop_duplicates(inplace=True)

    categorical_cols = df.select_dtypes(include='object').columns.tolist()
    if 'SeniorCitizen' not in categorical_cols:
        categorical_cols.append('SeniorCitizen')

    for col in categorical_cols:
        if df[col].dtype == 'object':
            if 'No internet service' in df[col].unique():
                df[col] = df[col].replace('No internet service', 'No')
            if 'No phone service' in df[col].unique():
                df[col] = df[col].replace('No phone service', 'No')
    print("Data cleaning and preprocessing complete.")
    df.to_csv('cleaned_data_airflow.csv', index=False) # Save intermediate for next task

def _feature_engineer_data():
    print("Loading cleaned data for feature engineering...")
    df = pd.read_csv('cleaned_data_airflow.csv') # Load from previous task

    binary_service_cols = ['PhoneService', 'MultipleLines', 'OnlineSecurity', 'OnlineBackup',
                           'DeviceProtection', 'TechSupport', 'StreamingTV', 'StreamingMovies']
    for col in binary_service_cols:
        df[col + '_numeric'] = df[col].map({'Yes': 1, 'No': 0})
    df['InternetService_numeric'] = df['InternetService'].map({'DSL': 1, 'Fiber optic': 1, 'No': 0})
    df['ServiceCount'] = df[['PhoneService_numeric', 'MultipleLines_numeric', 'InternetService_numeric',
                             'OnlineSecurity_numeric', 'OnlineBackup_numeric', 'DeviceProtection_numeric',
                             'TechSupport_numeric', 'StreamingTV_numeric', 'StreamingMovies_numeric']].sum(axis=1)
    df.drop(columns=[col + '_numeric' for col in binary_service_cols] + ['InternetService_numeric'], inplace=True)

    df['ChurnRiskScore'] = 0
    for col in ['Partner', 'Dependents', 'OnlineSecurity', 'OnlineBackup', 'DeviceProtection', 'TechSupport', 'StreamingTV', 'StreamingMovies']:
        df['ChurnRiskScore'] += df[col].apply(lambda x: 1 if x == 'No' else 0)
    df['ChurnRiskScore'] += df['PhoneService'].apply(lambda x: 1 if x == 'No' else 0)
    df['ChurnRiskScore'] += df['MultipleLines'].apply(lambda x: 1 if x == 'No' else 0)
    df['ChurnRiskScore'] += df['PaperlessBilling'].apply(lambda x: 1 if x == 'Yes' else 0)
    df['ChurnRiskScore'] += df['Contract'].apply(lambda x: 1 if x == 'Month-to-month' else 0)

    bins = [0, 12, 24, 48, 72]
    labels = ['0-12', '13-24', '25-48', '49-72']
    df['Tenure_bins'] = pd.cut(df['tenure'], bins=bins, labels=labels, right=False, include_lowest=True)

    df['AvgMonthlyCharge'] = df.apply(lambda row: row['MonthlyCharges'] if row['tenure'] == 0 else row['TotalCharges'] / row['tenure'], axis=1)
    df['PaymentMethodRisk'] = df['PaymentMethod'].apply(lambda x: 1 if x == 'Electronic check' else 0)
    df['HasInternetService'] = df['InternetService'].apply(lambda x: 1 if x != 'No' else 0)
    df['HasMultipleLines'] = df['MultipleLines'].apply(lambda x: 1 if x == 'Yes' else 0)

    security_service_cols = ['OnlineSecurity', 'DeviceProtection', 'TechSupport']
    for col in security_service_cols:
        df[col + '_numeric'] = df[col].map({'Yes': 1, 'No': 0})
    df['TotalServicesSecurity'] = df[['OnlineSecurity_numeric', 'DeviceProtection_numeric', 'TechSupport_numeric']].sum(axis=1)
    df.drop(columns=[col + '_numeric' for col in security_service_cols], inplace=True)

    df['HasSecurityServices'] = df['TotalServicesSecurity'].apply(lambda x: 1 if x > 0 else 0)
    df['IsMonthToMonth'] = df['Contract'].apply(lambda x: 1 if x == 'Month-to-month' else 0)

    print("Feature engineering complete.")
    df.to_csv('feature_engineered_data_airflow.csv', index=False) # Save intermediate for next task

def _run_great_expectations_validation():
    print("Loading feature-engineered data for validation...")
    df = pd.read_csv('feature_engineered_data_airflow.csv') # Load from previous task

    context = gx.get_context(project_root_dir='.')

    datasource_name = "my_pandas_datasource_airflow"
    datasource_config = {
        "name": datasource_name,
        "class_name": "Datasource",
        "module_name": "great_expectations.datasource",
        "execution_engine": {
            "class_name": "PandasExecutionEngine",
            "module_name": "great_expectations.execution_engine"
        },
        "data_connectors": {
            "default_inferred_data_connector_name": {
                "class_name": "InferredAssetFilesystemDataConnector",
                "base_directory": "../data", # Placeholder
                "default_regex": {
                    "pattern": ".*",
                    "group_names": ["data_asset_name"],
                },
            }
        }
    }
    context.add_or_update_datasource(**datasource_config)
    pandas_datasource = context.get_datasource(datasource_name=datasource_name)

    data_asset_name = "telco_churn_data_airflow"
    data_asset = pandas_datasource.add_dataframe_asset(name=data_asset_name, dataframe=df)

    expectation_suite_name = "telco_churn_suite_airflow"
    suite = context.add_or_update_expectation_suite(expectation_suite_name=expectation_suite_name)
    suite.expectations = []

    suite.add_expectation(ExpectationConfiguration("expect_column_to_exist", kwargs={"column": "customerID"}))
    suite.add_expectation(ExpectationConfiguration("expect_column_values_to_be_unique", kwargs={"column": "customerID"}))
    suite.add_expectation(ExpectationConfiguration("expect_column_values_to_be_of_type", kwargs={"column": "tenure", "type": "int64"}))
    suite.add_expectation(ExpectationConfiguration("expect_column_values_to_be_of_type", kwargs={"column": "MonthlyCharges", "type": "float64"}))
    suite.add_expectation(ExpectationConfiguration("expect_column_values_to_be_of_type", kwargs={"column": "TotalCharges", "type": "float64"}))
    suite.add_expectation(ExpectationConfiguration("expect_column_to_exist", kwargs={"column": "Churn"}))
    suite.add_expectation(ExpectationConfiguration("expect_column_values_to_not_be_null", kwargs={"column": "Churn"}))
    suite.add_expectation(ExpectationConfiguration("expect_column_values_to_be_in_set", kwargs={"column": "Churn", "value_set": ["Yes", "No"]}))
    for col in ['ServiceCount', 'ChurnRiskScore', 'HasInternetService', 'HasMultipleLines',
                'TotalServicesSecurity', 'HasSecurityServices', 'IsMonthToMonth']:
        suite.add_expectation(ExpectationConfiguration("expect_column_to_exist", kwargs={"column": col}))
        suite.add_expectation(ExpectationConfiguration("expect_column_values_to_be_of_type", kwargs={"column": col, "type": "int64"}))
        suite.add_expectation(ExpectationConfiguration("expect_column_values_to_be_in_set", kwargs={"column": col, "value_set": [0, 1]}))
    suite.add_expectation(ExpectationConfiguration("expect_column_to_exist", kwargs={"column": "Tenure_bins"}))
    suite.add_expectation(ExpectationConfiguration("expect_column_values_to_be_in_set", kwargs={"column": "Tenure_bins", "value_set": ['0-12', '13-24', '25-48', '49-72']}))

    context.update_expectation_suite(suite=suite)

    batch_request = data_asset.build_batch_request()
    validator = context.get_validator(
        batch_request=batch_request,
        expectation_suite=suite
    )
    results = validator.validate()
    print("Great Expectations validation complete.")
    # In a real Airflow setup, you might parse results and branch based on success/failure
    if not results.success:
        raise ValueError("Great Expectations validation failed!")

