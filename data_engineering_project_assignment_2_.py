from datetime import datetime, timedelta
import sqlite3
import pandas as pd
import great_expectations as gx

from airflow import DAG
from airflow.decorators import task

default_args = {
    'owner': 'data_engineering',
    'depends_on_past': False,
    'retries': 1,
    'retry_delay': timedelta(minutes=1),
}

with DAG(
    dag_id="telco_churn_data_engineering_pipeline",
    default_args=default_args,
    description="End-to-end Telco Churn Data Pipeline with Transformations & GX Quality Checks",
    schedule_interval="@daily",
    start_date=datetime(2026, 1, 1),
    catchup=False,
    tags=["data_engineering", "dbt", "great_expectations"],
) as dag:

    # --------------------------------------------------------------------------
    # TASK 1: INGEST DATA
    # --------------------------------------------------------------------------
    @task
    def ingest_data() -> str:
        """Downloads the raw IBM Telco Churn CSV data."""
        url = "https://raw.githubusercontent.com/IBM/telco-customer-churn-on-icp-for-data/master/data/WA_Fn-UseC_-Telco-Customer-Churn.csv"
        df = pd.read_csv(url)
        raw_path = "/content/raw_telco_churn.csv"
        df.to_csv(raw_path, index=False)
        print(f"[Ingest Data] Downloaded {len(df)} rows to {raw_path}")
        return raw_path

    # --------------------------------------------------------------------------
    # TASK 2: STORE RAW DATA
    # --------------------------------------------------------------------------
    @task
    def store_raw_data(raw_csv_path: str) -> dict:
        """Stores the raw ingested data into SQLite and Parquet formats."""
        df = pd.read_csv(raw_csv_path)

        # SQLite storage
        sqlite_db_path = "/content/telco_churn.db"
        conn = sqlite3.connect(sqlite_db_path)
        df.to_sql("raw_telco_churn", conn, index=False, if_exists="replace")
        conn.close()

        # Parquet storage
        raw_parquet_path = "/content/raw_telco_churn.parquet"
        df.to_parquet(raw_parquet_path, index=False)

        print(f"[Store Raw Data] Saved raw data to SQLite ({sqlite_db_path}) and Parquet ({raw_parquet_path})")
        return {"sqlite_path": sqlite_db_path, "parquet_path": raw_parquet_path}

    # --------------------------------------------------------------------------
    # TASK 3: CLEAN AND PREPROCESS DATA
    # --------------------------------------------------------------------------
    @task
    def clean_and_preprocess(paths: dict) -> str:
        """Handles missing values, data types, and standardizes categorical features."""
        conn = sqlite3.connect(paths["sqlite_path"])
        df = pd.read_sql_query("SELECT * FROM raw_telco_churn", conn)
        conn.close()

        # Clean TotalCharges and convert to numeric
        df["TotalCharges"] = pd.to_numeric(df["TotalCharges"].str.strip(), errors="coerce").fillna(0.0)

        # Standardize categorical values
        binary_cols = ["Partner", "Dependents", "PhoneService", "PaperlessBilling", "Churn"]
        for col in binary_cols:
            df[col] = df[col].map({"Yes": 1, "No": 0}).fillna(0).astype(int)

        cleaned_csv_path = "/content/cleaned_telco_churn.csv"
        df.to_csv(cleaned_csv_path, index=False)
        print(f"[Clean & Preprocess] Processed {len(df)} records.")
        return cleaned_csv_path

    # --------------------------------------------------------------------------
    # TASK 4: FEATURE ENGINEERING
    # --------------------------------------------------------------------------
    @task
    def feature_engineering(cleaned_csv_path: str) -> str:
        """Creates 10+ domain-relevant features for ML training."""
        df = pd.read_csv(cleaned_csv_path)

        # 10+ Derived Domain Features
        df["is_senior"] = df["SeniorCitizen"].astype(int)
        df["is_month_to_month"] = (df["Contract"] == "Month-to-month").astype(int)
        df["is_one_year"] = (df["Contract"] == "One year").astype(int)
        df["is_two_year"] = (df["Contract"] == "Two year").astype(int)
        df["is_electronic_check"] = (df["PaymentMethod"] == "Electronic check").astype(int)
        df["has_internet"] = (df["InternetService"] != "No").astype(int)
        df["has_fiber_optic"] = (df["InternetService"] == "Fiber optic").astype(int)
        df["has_online_security"] = (df["OnlineSecurity"] == "Yes").astype(int)
        df["has_tech_support"] = (df["TechSupport"] == "Yes").astype(int)
        df["avg_monthly_charge"] = (df["TotalCharges"] / (df["tenure"] + 1)).round(2)
        df["tenure_years"] = (df["tenure"] / 12).round(2)

        fe_csv_path = "/content/feature_engineered_telco_churn.csv"
        df.to_csv(fe_csv_path, index=False)
        print(f"[Feature Engineering] Generated 11 engineered features.")
        return fe_csv_path

    # --------------------------------------------------------------------------
    # TASK 5: QUALITY CHECKS (GREAT EXPECTATIONS)
    # --------------------------------------------------------------------------
    @task
    def quality_checks(fe_csv_path: str) -> str:
        """Runs Great Expectations data quality validation against all rows."""
        df = pd.read_csv(fe_csv_path)

        context = gx.get_context()
        data_source = context.data_sources.add_pandas(name="airflow_gx_source")
        data_asset = data_source.add_dataframe_asset(name="telco_fe_asset")
        batch_definition = data_asset.add_batch_definition_entire_dataframe("full_batch")
        batch = batch_definition.get_batch(batch_parameters={"dataframe": df})

        expectations = [
            gx.expectations.ExpectColumnValuesToNotBeNull(column="customerID"),
            gx.expectations.ExpectColumnValuesToBeUnique(column="customerID"),
            gx.expectations.ExpectColumnValuesToBeBetween(column="tenure", min_value=0, max_value=120),
            gx.expectations.ExpectColumnValuesToBeInSet(column="Churn", value_set=[0, 1]),
            gx.expectations.ExpectColumnValuesToBeBetween(column="is_month_to_month", min_value=0, max_value=1),
            gx.expectations.ExpectColumnValuesToBeGreaterThan(column="avg_monthly_charge", value=0)
        ]

        for exp in expectations:
            res = batch.validate(exp)
            assert res.success, f"Quality check failed for {exp.__class__.__name__} on column {getattr(exp, 'column', '')}"

        print(f"[Quality Checks] All Great Expectations validation assertions passed!")
        return fe_csv_path

    # --------------------------------------------------------------------------
    # TASK 6: SAVE ML-READY DATA
    # --------------------------------------------------------------------------
    @task
    def save_ml_ready_data(validated_csv_path: str) -> str:
        """Stores the final processed dataset into Parquet and SQLite."""
        df = pd.read_csv(validated_csv_path)

        final_parquet_path = "/content/ml_ready_telco_churn.parquet"
        df.to_parquet(final_parquet_path, index=False)

        conn = sqlite3.connect("/content/telco_churn.db")
        df.to_sql("ml_ready_telco_churn", conn, index=False, if_exists="replace")
        conn.close()

        print(f"[Save ML-Ready Data] Pipeline Complete! Final dataset saved to {final_parquet_path}")
        return final_parquet_path

    # --------------------------------------------------------------------------
    # DEFINE TASK DEPENDENCIES
    # --------------------------------------------------------------------------
    raw_csv = ingest_data()
    stored_paths = store_raw_data(raw_csv)
    cleaned_csv = clean_and_preprocess(stored_paths)
    fe_csv = feature_engineering(cleaned_csv)
    validated_csv = quality_checks(fe_csv)
    final_output = save_ml_ready_data(validated_csv)

# ==============================================================================
# 3. TEST DAG EXECUTION LOCALLY IN COLAB
# ==============================================================================
print("\n--- TRIGGERING AIRFLOW DAG EXECUTION IN COLAB ---")
dag.test()

