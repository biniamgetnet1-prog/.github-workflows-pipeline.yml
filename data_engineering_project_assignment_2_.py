from prefect import flow, task
import pandas as pd
import sqlite3

@task
def load_csv_data(file_path: str) -> pd.DataFrame:
    """Loads data from a CSV file into a pandas DataFrame."""
    print(f"Loading CSV data from {file_path}...")
    df_csv = pd.read_csv(file_path)
    print(f"CSV data loaded. Shape: {df_csv.shape}")
    return df_csv

@task
def load_sqlite_data(db_name: str, table_name: str) -> pd.DataFrame:
    """Loads data from a SQLite table into a pandas DataFrame."""
    print(f"Loading SQLite data from table {table_name} in {db_name}...")
    conn = sqlite3.connect(db_name)
    df_sqlite = pd.read_sql_query(f"SELECT * FROM {table_name}", conn)
    conn.close()
    print(f"SQLite data loaded. Shape: {df_sqlite.shape}")
    return df_sqlite

@task
def merge_dataframes(df1: pd.DataFrame, df2: pd.DataFrame) -> pd.DataFrame:
    """Merges two pandas DataFrames based on 'customerID'."""
    print("Merging dataframes...")
    # Assuming 'customerID' is the common column and datasets are additive
    # If you expect to merge on different criteria or handle duplicates differently,
    # this logic would need adjustment.
    df_merged = pd.concat([df1, df2]).drop_duplicates(subset=['customerID']).reset_index(drop=True)
    print(f"Dataframes merged. Combined shape: {df_merged.shape}")
    return df_merged

@flow(name="Telco Churn Data Merge Flow")
def telco_data_merge_flow():
    """Orchestrates the loading and merging of Telco Churn data."""
