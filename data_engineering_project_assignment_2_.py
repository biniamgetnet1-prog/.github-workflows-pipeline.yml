def calculate_churn_rate(data, column):
    """
    Calculate the percentage of customers who churn
    within each category.
    """

    result = pd.crosstab(
        data[column],
        data["Churn"],
        normalize="index"
    ) * 100

    if "Yes" in result.columns:
        return result["Yes"]

    return pd.Series(0, index=result.index)


